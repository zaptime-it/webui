#!/usr/bin/env python3
"""Generate src/lib/types/settings.generated.ts from the firmware's kFields table.

The hand-maintained Settings TypeScript shape in
`src/lib/types/settings.ts` doesn't carry bounds, boot-only flags, or
defaults. The firmware does — `kFields` in
`components/settings/include/settings/schema.hpp` is the canonical
table. This script parses that table and emits a sibling TS module
exposing the same metadata, so the WebUI can:

  * tag inputs that flip a `boot_only` field with the "restart required"
    hint without copy-pasting the list,
  * apply min/max ranges to NumberField inputs without the firmware
    rejecting the PATCH after a round-trip,
  * derive defaults that the WebUI's reset-to-defaults button can use.

The script is read-only: it does *not* generate the Settings *type*
itself. That stays hand-maintained because some fields (timePerScreen,
*Set booleans, gitTag/gitRev/lastBuildTime) are emitted by the firmware
but absent from kFields, and squeezing the GET-only fields into the
PATCH-table would conflate two different contracts.

Usage:
    python3 scripts/generate-settings-meta.py [--firmware ../btclock_v4]

The default firmware path resolves to ../btclock_v4 relative to the
WebUI repo. Override for monorepo layouts. CI calls this without args;
local devs typically run it after pulling firmware schema changes.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Iterator


# ---- Parsers ---------------------------------------------------------------

PREF_KEYS_RE = re.compile(
    r'inline constexpr const char\* (?P<sym>k[A-Za-z0-9]+) = "(?P<key>[^"]+)"'
)
KFIELDS_RE = re.compile(
    r"\{\s*prefs::(?P<sym>k[A-Za-z0-9]+),\s*"
    r"FieldKind::(?P<kind>k[A-Za-z]+),\s*"
    r"(?P<boot_only>true|false),\s*"
    r"(?P<min>0x[0-9A-Fa-f]+u?|\d+|\d+\s*\*\s*\d+),\s*"
    r"(?P<max>0x[0-9A-Fa-f]+u?|\d+|\d+\s*\*\s*\d+),\s*"
    r"(?P<default_bool>true|false),\s*"
    r"(?P<default_int>0x[0-9A-Fa-f]+u?|-?\d+|\d+\s*\*\s*\d+),\s*"
    r'(?:"(?P<default_str>[^"]*)"|\{\})'
    r"\s*\}",
    re.MULTILINE,
)

KIND_TO_TS: dict[str, str] = {
    "kString": "string",
    "kUint": "number",
    "kInt": "number",
    "kBool": "boolean",
    "kUChar": "number",
}


def parse_int(raw: str) -> int:
    """Handle `15 * 60`, `0xFF`, decimal."""
    raw = raw.strip().rstrip("u")
    if "*" in raw:
        a, b = (int(x.strip()) for x in raw.split("*"))
        return a * b
    return int(raw, 16) if raw.startswith("0x") else int(raw)


def parse_pref_keys(text: str) -> dict[str, str]:
    return {m.group("sym"): m.group("key") for m in PREF_KEYS_RE.finditer(text)}


def parse_kfields(text: str, key_map: dict[str, str]) -> Iterator[dict]:
    for m in KFIELDS_RE.finditer(text):
        sym = m.group("sym")
        if sym not in key_map:
            sys.exit(f"kFields references unknown prefs::{sym} — pref_keys out of sync?")
        yield {
            "key": key_map[sym],
            "kind": KIND_TO_TS[m.group("kind")],
            "bootOnly": m.group("boot_only") == "true",
            "minValue": parse_int(m.group("min")),
            "maxValue": parse_int(m.group("max")),
            "defaultBool": m.group("default_bool") == "true",
            "defaultInt": parse_int(m.group("default_int")),
            "defaultStr": m.group("default_str") or "",
        }


# ---- Emitter ---------------------------------------------------------------

HEADER = """\
// AUTO-GENERATED by scripts/generate-settings-meta.py — DO NOT EDIT.
//
// Run `pnpm generate:settings-meta` after a firmware schema change.
// Source: components/settings/include/settings/schema.hpp::kFields in
// the btclock firmware repo.

export type SettingsFieldKind = 'string' | 'number' | 'boolean';

export interface SettingsFieldMeta {
\tkey: string;
\tkind: SettingsFieldKind;
\tbootOnly: boolean;
\tminValue: number;
\tmaxValue: number;
\tdefaultBool: boolean;
\tdefaultInt: number;
\tdefaultStr: string;
}

"""


def emit(fields: list[dict]) -> str:
    out = [HEADER, "export const settingsFieldMeta: readonly SettingsFieldMeta[] = ["]
    for f in fields:
        out.append(
            "\t{ "
            + f"key: '{f['key']}', "
            + f"kind: '{f['kind']}', "
            + f"bootOnly: {'true' if f['bootOnly'] else 'false'}, "
            + f"minValue: {f['minValue']}, "
            + f"maxValue: {f['maxValue']}, "
            + f"defaultBool: {'true' if f['defaultBool'] else 'false'}, "
            + f"defaultInt: {f['defaultInt']}, "
            + f"defaultStr: {f['defaultStr']!r}"
            + " },"
        )
    out.append("];\n")
    out.append(
        "export const settingsFieldsByKey: Readonly<Record<string, SettingsFieldMeta>> = "
        "Object.freeze(\n"
        "\tObject.fromEntries(settingsFieldMeta.map((f) => [f.key, f]))\n);\n"
    )
    out.append(
        "export const isBootOnly = (key: string): boolean =>\n"
        "\tsettingsFieldsByKey[key]?.bootOnly === true;\n"
    )
    return "\n".join(out)


# ---- Driver ----------------------------------------------------------------


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    here = Path(__file__).resolve().parent.parent
    parser.add_argument(
        "--firmware",
        type=Path,
        default=here.parent / "btclock_v4",
        help="Path to the btclock firmware checkout (default: ../btclock_v4)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=here / "src" / "lib" / "types" / "settings.generated.ts",
    )
    args = parser.parse_args()

    schema_h = args.firmware / "components/settings/include/settings/schema.hpp"
    keys_h = args.firmware / "components/settings/include/settings/pref_keys.hpp"
    if not schema_h.is_file():
        sys.exit(f"schema.hpp not found at {schema_h}; pass --firmware <path>")
    if not keys_h.is_file():
        sys.exit(f"pref_keys.hpp not found at {keys_h}")

    key_map = parse_pref_keys(keys_h.read_text())
    fields = sorted(parse_kfields(schema_h.read_text(), key_map), key=lambda f: f["key"])
    if not fields:
        sys.exit("Parsed zero fields — regex drift, schema.hpp format changed.")

    args.out.write_text(emit(fields))
    out_label = args.out
    try:
        out_label = args.out.resolve().relative_to(here)
    except ValueError:
        # --out points outside the repo (CI's check:settings-meta writes to
        # /tmp). Fall back to the absolute path so the message stays useful.
        pass
    print(f"wrote {len(fields)} fields → {out_label}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
